"""Build immutable, right-sized Tower Rush runtime textures from source assets."""
from pathlib import Path
from PIL import Image
from io import BytesIO
import hashlib, json

root = Path(__file__).resolve().parents[2]
source = root / 'artifacts/3d-game/public/media/tower-rush'
output = source / 'optimized'
output.mkdir(exist_ok=True)
assets = {}
before = after = 0
seen_sources = set()

def asset(key, relative, size, quality=84, lossless=False):
    global before, after
    file = source / relative
    picture = Image.open(file)
    picture.thumbnail(size, Image.Resampling.LANCZOS)
    buffer = BytesIO()
    picture.save(buffer, format='WEBP', quality=quality, lossless=lossless, method=6)
    data = buffer.getvalue()
    name = f'{key}-{hashlib.sha256(data).hexdigest()[:12]}.webp'
    (output / name).write_bytes(data)
    assets[key] = f'media/tower-rush/optimized/{name}'
    if file not in seen_sources:
        before += file.stat().st_size
        seen_sources.add(file)
    after += len(data)

asset('site', 'site-photographic-v3.webp', (1280, 720), 82)
asset('environment', 'site-photographic-v3.webp', (512, 256), 76)
asset('dust', 'materials/dust.png', (64, 64), lossless=True)
for kind in ['wood', 'brick', 'stone', 'metal', 'ground']:
    asset(f'{kind}Color', f'materials/{kind}-color.webp', (256, 256), 82)
    asset(f'{kind}Normal', f'materials/{kind}-normal.png', (128, 128), 90)
    asset(f'{kind}Roughness', f'materials/{kind}-roughness.webp', (128, 128), 78)
for i in range(6):
    asset(f'facade{i}', f'materials/facade-v3-{i}.webp', (384, 267), 85)

module = root / 'artifacts/3d-game/src/components/instant/towerAssets.ts'
module.write_text('// Generated by tools/tower-assets/optimize_runtime.py.\nexport const towerAssets = ' + json.dumps(assets, indent=2) + ' as const;\nexport const towerAssetUrl = (key: keyof typeof towerAssets) => `${import.meta.env.BASE_URL}${towerAssets[key]}`;\n', encoding='utf-8')
(output / 'manifest.json').write_text(json.dumps({'beforeBytes': before, 'afterBytes': after, 'assets': assets}, indent=2))
print(json.dumps({'beforeBytes': before, 'afterBytes': after, 'reductionPercent': round(100 * (1 - after / before), 1), 'files': len(assets)}))
