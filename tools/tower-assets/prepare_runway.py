"""Build versioned, compressed runtime assets from the Runway reference art."""
from pathlib import Path
from PIL import Image
from io import BytesIO
import hashlib, json

root = Path(__file__).resolve().parents[2]
source = Path(__file__).parent / 'runway-v4'
output = root / 'artifacts/3d-game/public/media/tower-rush/optimized'
assets = json.loads((output / 'manifest.json').read_text())['assets']
sizes = {'Background': (1536, 864), 'Mobile': (768, 1024), 'ochre': (384, 512), 'clock': (384, 512), 'shop': (384, 512), 'blue': (384, 512)}
paths = {}
for name, size in sizes.items():
    picture = Image.open(source / (name + '.webp')).convert('RGB')
    picture.thumbnail(size, Image.Resampling.LANCZOS)
    buffer = BytesIO(); picture.save(buffer, format='WEBP', quality=86, method=6)
    data = buffer.getvalue()
    file = f'runway-{name.lower()}-{hashlib.sha256(data).hexdigest()[:12]}.webp'
    (output / file).write_bytes(data); paths[name] = 'media/tower-rush/optimized/' + file
assets['site'] = paths['Background']; assets['siteMobile'] = paths['Mobile']
for i, name in enumerate(['ochre', 'clock', 'blue', 'ochre', 'shop', 'blue']):
    assets[f'facade{i}'] = paths[name]
module = root / 'artifacts/3d-game/src/components/instant/towerAssets.ts'
module.write_text('// Generated by tools/tower-assets/prepare_runway.py.\nexport const towerAssets = ' + json.dumps(assets, indent=2) + ' as const;\nexport const towerAssetUrl = (key: keyof typeof towerAssets) => `${import.meta.env.BASE_URL}${towerAssets[key]}`;\n', encoding='utf-8')
record = {'assets': assets, 'newArtBytes': sum((root / 'artifacts/3d-game/public' / p).stat().st_size for p in set(paths.values()))}
(source / 'runtime.json').write_text(json.dumps(record, indent=2))
print(json.dumps({'newArtBytes': record['newArtBytes'], 'uniqueNewAssets': len(paths)}))
